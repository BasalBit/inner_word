#!/bin/bash
# Builds The Writer as an ad-hoc signed macOS app and a compressed disk image.
#
#   scripts/bundle.sh                 native architecture
#   scripts/bundle.sh --universal     arm64 + x86_64 in one binary (lipo)
#   scripts/bundle.sh --no-smoke-test skip launching the bundled app (headless machines)
#
# Output (replaced on every run):
#   dist/The Writer.app
#   dist/The-Writer-<version>-<arm64|x86_64|universal>.dmg
# THE_WRITER_DIST_DIR=<dir> writes both there instead of dist/ (a trial build that must not
# replace the images of a release with the same version number).
#
# The bundle holds two executables: the app (Contents/MacOS/the-writer) and the command
# line tool for agents (Contents/MacOS/writer, the binary of crates/writer-cli), built from
# the same commit so they always have the same version. Agents call the tool by its path
# inside the bundle; nothing is installed outside it.
#
# There is no Apple developer certificate: the app is signed with the ad-hoc identity
# ("-"), which Apple Silicon requires to run code at all, and it is not notarised.
# Recipients approve it once by hand; packaging/Read Me First.txt (copied into the disk
# image) explains how.
#
# The script is non-interactive and stops at the first failing step.

set -euo pipefail

APP_NAME="The Writer"
BIN_NAME="the-writer"
CRATE="writer-app"
TOOL_NAME="writer"
TOOL_CRATE="writer-cli"
BUNDLE_ID="app.thewriter.TheWriter"
SMOKE_TIMEOUT_SECS=60

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PACKAGING="$ROOT/packaging"
DIST="${THE_WRITER_DIST_DIR:-$ROOT/dist}"
PLIST_SRC="$PACKAGING/Info.plist"
ICNS="$PACKAGING/TheWriter.icns"
README="$PACKAGING/Read Me First.txt"
PLISTBUDDY=/usr/libexec/PlistBuddy

UNIVERSAL=0
SMOKE=1
for arg in "$@"; do
    case "$arg" in
        --universal) UNIVERSAL=1 ;;
        --no-smoke-test) SMOKE=0 ;;
        -h|--help) sed -n '2,25p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "bundle: unknown argument: $arg (try --help)" >&2; exit 2 ;;
    esac
done

step() { printf '\n==> %s\n' "$*"; }
die() { echo "bundle: error: $*" >&2; exit 1; }

[[ "$(uname -s)" == "Darwin" ]] || die "this script only runs on macOS"
for tool in cargo codesign hdiutil lipo vtool shasum xattr ditto plutil "$PLISTBUDDY"; do
    command -v "$tool" >/dev/null || die "required tool not found: $tool"
done
for f in "$PLIST_SRC" "$ICNS" "$README"; do
    [[ -f "$f" ]] || die "missing $f (the icon is generated by scripts/make-icon.sh)"
done

WORK="$(mktemp -d "${TMPDIR:-/tmp}/the-writer-bundle.XXXXXX")"
MOUNT_POINT=""
APP_PID=""
cleanup() {
    local status=$?
    if [[ -n "$APP_PID" ]] && kill -0 "$APP_PID" 2>/dev/null; then kill -9 "$APP_PID" 2>/dev/null || true; fi
    if [[ -n "$MOUNT_POINT" && -d "$MOUNT_POINT/$APP_NAME.app" ]]; then
        hdiutil detach "$MOUNT_POINT" -force -quiet || true
    fi
    rm -rf "$WORK"
    if [[ $status -ne 0 ]]; then echo "bundle: FAILED (exit $status)" >&2; fi
}
trap cleanup EXIT

cd "$ROOT"

# ---------------------------------------------------------------- version and targets
VERSION="$(cargo pkgid -p "$CRATE" | sed -E 's/.*[#@]//')"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+ ]] || die "could not read the version of $CRATE (got '$VERSION')"

MIN_MACOS="$("$PLISTBUDDY" -c 'Print :LSMinimumSystemVersion' "$PLIST_SRC")"
[[ -n "$MIN_MACOS" ]] || die "LSMinimumSystemVersion missing from $PLIST_SRC"
export MACOSX_DEPLOYMENT_TARGET="$MIN_MACOS"

HOST_TARGET="$(rustc -vV | sed -n 's/^host: //p')"
case "$HOST_TARGET" in
    aarch64-apple-darwin) NATIVE_ARCH=arm64 ;;
    x86_64-apple-darwin) NATIVE_ARCH=x86_64 ;;
    *) die "unsupported host target: $HOST_TARGET" ;;
esac
TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"

if [[ $UNIVERSAL -eq 1 ]]; then ARCH_LABEL=universal; else ARCH_LABEL="$NATIVE_ARCH"; fi
APP="$DIST/$APP_NAME.app"
DMG="$DIST/The-Writer-$VERSION-$ARCH_LABEL.dmg"

echo "The Writer $VERSION, $ARCH_LABEL, minimum macOS $MIN_MACOS"

# ---------------------------------------------------------------- build
# Both executables, each for every architecture asked for.
BINARY="$WORK/$BIN_NAME"
TOOL="$WORK/$TOOL_NAME"
if [[ $UNIVERSAL -eq 1 ]]; then
    SLICES=()
    TOOL_SLICES=()
    for target in aarch64-apple-darwin x86_64-apple-darwin; do
        step "Building release binaries for $target"
        cargo build --release -p "$CRATE" --bin "$BIN_NAME" --target "$target"
        cargo build --release -p "$TOOL_CRATE" --bin "$TOOL_NAME" --target "$target"
        SLICES+=("$TARGET_DIR/$target/release/$BIN_NAME")
        TOOL_SLICES+=("$TARGET_DIR/$target/release/$TOOL_NAME")
    done
    step "Joining the two architectures with lipo"
    lipo -create "${SLICES[@]}" -output "$BINARY"
    lipo -create "${TOOL_SLICES[@]}" -output "$TOOL"
else
    step "Building release binaries for $HOST_TARGET"
    cargo build --release -p "$CRATE" --bin "$BIN_NAME"
    cargo build --release -p "$TOOL_CRATE" --bin "$TOOL_NAME"
    cp "$TARGET_DIR/release/$BIN_NAME" "$BINARY"
    cp "$TARGET_DIR/release/$TOOL_NAME" "$TOOL"
fi

# The deployment target the linker recorded in each slice must not be newer than what
# Info.plist promises. (arm64 is always at least 11.0: no older macOS runs on it.)
# (Command output is captured before it is filtered: with pipefail, a filter that stops
# reading early would turn into a SIGPIPE failure of the command in front of it.)
version_le() {
    local sorted
    sorted="$(printf '%s\n%s\n' "$1" "$2" | sort -t. -k1,1n -k2,2n -k3,3n)"
    [[ "${sorted%%$'\n'*}" == "$1" ]]
}
# check_binary <file> <name>: the architectures and the minimum macOS of each slice.
check_binary() {
    local file="$1" name="$2" archs arch build_info minos allowed
    archs="$(lipo -archs "$file")"
    echo "$name: architectures: $archs"
    if [[ $UNIVERSAL -eq 1 ]]; then
        [[ "$archs" == *arm64* && "$archs" == *x86_64* ]] || die "the universal $name is missing a slice: $archs"
    else
        [[ "$archs" == "$NATIVE_ARCH" ]] || die "expected a $NATIVE_ARCH $name, got: $archs"
    fi
    for arch in $archs; do
        build_info="$(vtool -arch "$arch" -show-build "$file")"
        minos="$(awk '($1 == "minos" || $1 == "version") && !seen { print $2; seen = 1 }' <<<"$build_info")"
        [[ -n "$minos" ]] || die "could not read the minimum OS version of the $arch slice of $name"
        allowed="$MIN_MACOS"
        if [[ "$arch" == arm64 ]] && version_le "$MIN_MACOS" 11.0; then allowed=11.0; fi
        echo "$name: minimum macOS recorded in the $arch slice: $minos"
        version_le "$minos" "$allowed" || die "the $arch slice of $name needs macOS $minos, but Info.plist promises $MIN_MACOS"
    done
}
check_binary "$BINARY" "$BIN_NAME"
check_binary "$TOOL" "$TOOL_NAME"

# ---------------------------------------------------------------- assemble the .app
step "Assembling $APP_NAME.app"
STAGE_APP="$WORK/$APP_NAME.app"
mkdir -p "$STAGE_APP/Contents/MacOS" "$STAGE_APP/Contents/Resources"
cp "$BINARY" "$STAGE_APP/Contents/MacOS/$BIN_NAME"
cp "$TOOL" "$STAGE_APP/Contents/MacOS/$TOOL_NAME"
chmod 755 "$STAGE_APP/Contents/MacOS/$BIN_NAME" "$STAGE_APP/Contents/MacOS/$TOOL_NAME"
cp "$ICNS" "$STAGE_APP/Contents/Resources/TheWriter.icns"
cp "$PLIST_SRC" "$STAGE_APP/Contents/Info.plist"
printf 'APPL????' > "$STAGE_APP/Contents/PkgInfo"
"$PLISTBUDDY" -c "Set :CFBundleShortVersionString $VERSION" "$STAGE_APP/Contents/Info.plist"
"$PLISTBUDDY" -c "Set :CFBundleVersion $VERSION" "$STAGE_APP/Contents/Info.plist"
plutil -lint "$STAGE_APP/Contents/Info.plist" >/dev/null
[[ "$("$PLISTBUDDY" -c 'Print :CFBundleIdentifier' "$STAGE_APP/Contents/Info.plist")" == "$BUNDLE_ID" ]] \
    || die "Info.plist does not carry the bundle id $BUNDLE_ID"
[[ "$("$PLISTBUDDY" -c 'Print :CFBundleExecutable' "$STAGE_APP/Contents/Info.plist")" == "$BIN_NAME" ]] \
    || die "Info.plist does not name the executable $BIN_NAME"
# Extended attributes (Finder info, resource forks) make codesign refuse the bundle.
xattr -cr "$STAGE_APP"

# ---------------------------------------------------------------- sign
step "Signing (ad-hoc)"
# Inside out: the tool is code nested in the bundle and has to carry its own signature
# before the bundle is sealed over it.
codesign --force --sign - --identifier "$BUNDLE_ID.$TOOL_NAME" --timestamp=none "$STAGE_APP/Contents/MacOS/$TOOL_NAME"
codesign --force --sign - --identifier "$BUNDLE_ID" --timestamp=none "$STAGE_APP"
codesign --verify --deep --strict --verbose=2 "$STAGE_APP"
codesign --verify --strict --verbose=2 "$STAGE_APP/Contents/MacOS/$TOOL_NAME"
SIGN_INFO="$(codesign --display --verbose=2 "$STAGE_APP" 2>&1)"
grep -E '^(Identifier|Format|Signature|CodeDirectory)' <<<"$SIGN_INFO" || true
grep -q '^Signature=adhoc$' <<<"$SIGN_INFO" || die "the bundle is not ad-hoc signed"
TOOL_SIGN_INFO="$(codesign --display --verbose=2 "$STAGE_APP/Contents/MacOS/$TOOL_NAME" 2>&1)"
grep -E '^(Identifier|Signature)' <<<"$TOOL_SIGN_INFO" || true
grep -q '^Signature=adhoc$' <<<"$TOOL_SIGN_INFO" || die "the $TOOL_NAME tool in the bundle is not ad-hoc signed"
grep -q "^Identifier=$BUNDLE_ID.$TOOL_NAME\$" <<<"$TOOL_SIGN_INFO" || die "the $TOOL_NAME tool in the bundle does not carry its identifier"

mkdir -p "$DIST"
rm -rf "$APP"
ditto "$STAGE_APP" "$APP"
codesign --verify --deep --strict "$APP"
codesign --verify --strict "$APP/Contents/MacOS/$TOOL_NAME"
echo "app: $APP"
echo "tool: $APP/Contents/MacOS/$TOOL_NAME"

# ---------------------------------------------------------------- smoke test
# wait_for_app <log>: waits until the app started in the background ($APP_PID) has ended,
# and fails when it does not within the time limit or ends with an error.
wait_for_app() {
    local log="$1" waited=0 status=0
    while kill -0 "$APP_PID" 2>/dev/null; do
        if [[ $waited -ge $((SMOKE_TIMEOUT_SECS * 2)) ]]; then
            kill -9 "$APP_PID" 2>/dev/null || true
            sed 's/^/    /' "$log" >&2
            die "the app did not quit within ${SMOKE_TIMEOUT_SECS}s"
        fi
        sleep 0.5
        waited=$((waited + 1))
    done
    wait "$APP_PID" || status=$?
    APP_PID=""
    sed 's/^/    /' "$log"
    [[ $status -eq 0 ]] || die "the app exited with status $status"
}

if [[ $SMOKE -eq 1 ]]; then
    step "Smoke test: launching the bundled binary against a temporary library"
    SMOKE_DATA="$WORK/smoke-data"
    SMOKE_LOG="$WORK/smoke.log"
    THE_WRITER_DATA_DIR="$SMOKE_DATA" THE_WRITER_AUTOMATION="wait:1500; info; quit" \
        "$APP/Contents/MacOS/$BIN_NAME" >"$SMOKE_LOG" 2>&1 &
    APP_PID=$!
    wait_for_app "$SMOKE_LOG"
    [[ -d "$SMOKE_DATA" ]] || die "the app did not create its data directory ($SMOKE_DATA)"
    echo "smoke test passed: launched, ran the automation script, quit with status 0"

    # The tool, as an agent runs it: by its path in the bundle, on a library of its own.
    # (Never the real one: every call names the temporary directory, and the variable is
    # set too, so that a call that lost its option still could not reach it.)
    step "Smoke test: the bundled $TOOL_NAME tool against a temporary library"
    BUNDLED_TOOL="$APP/Contents/MacOS/$TOOL_NAME"
    TOOL_DATA="$WORK/tool-data"
    TOOL_OUT="$WORK/tool.out"
    TOOL_LOG="$WORK/tool-app.log"
    export THE_WRITER_DATA_DIR="$TOOL_DATA"
    # run_tool <expected exit code> <arguments>: output and errors go to $TOOL_OUT.
    run_tool() {
        local expected="$1" status=0
        shift
        "$BUNDLED_TOOL" --library "$TOOL_DATA" "$@" >"$TOOL_OUT" 2>&1 || status=$?
        if [[ $status -ne $expected ]]; then
            sed 's/^/    /' "$TOOL_OUT" >&2
            die "$TOOL_NAME $* exited with status $status, expected $expected"
        fi
    }
    tool_said() {
        grep -q -- "$1" "$TOOL_OUT" || { sed 's/^/    /' "$TOOL_OUT" >&2; die "the output of the tool does not have: $1"; }
    }

    run_tool 0 --version
    tool_said "^$TOOL_NAME $VERSION\$"
    echo "version: $(cat "$TOOL_OUT")"

    # With the app closed the tool does everything: create a document, read it back.
    run_tool 0 create "Tool smoke test" --content $'# Tool smoke test\n\nWritten by the bundled tool.'
    sed 's/^/    /' "$TOOL_OUT"
    run_tool 0 get "Tool smoke test"
    tool_said "Written by the bundled tool."
    echo "created a document and read it back"

    # With the app open on that library: the app shows what the tool wrote, reading still
    # works, and a change the tool makes is carried out by the app: it arrives in the
    # window and in the library; a page the tool adds (its check in WebKit, in a child of the
    # bundled tool) is stored by the app. The script of the app waits for three changes by agents,
    # prints what it shows, switches "Agents can make changes while The Writer is open"
    # off and waits to be told to quit.
    THE_WRITER_AUTOMATION="wait:1500; keys:cmd-p; type:Tool smoke; keys:enter; wait:300; state; agents:3:180000; wait:300; state; keys:cmd-p; type:Tool smoke; keys:enter; wait:300; dump; agents:off; state; log:the switch is off; wait:120000; quit" \
        "$APP/Contents/MacOS/$BIN_NAME" >"$TOOL_LOG" 2>&1 &
    APP_PID=$!
    # wait_for_log <text> <what>: until the app's log has the text.
    wait_for_log() {
        local waited=0
        until grep -q -- "$1" "$TOOL_LOG" 2>/dev/null; do
            kill -0 "$APP_PID" 2>/dev/null || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the app ended before $2"; }
            [[ $waited -lt $((SMOKE_TIMEOUT_SECS * 2)) ]] || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the app did not get to where $2 within ${SMOKE_TIMEOUT_SECS}s"; }
            sleep 0.5
            waited=$((waited + 1))
        done
    }
    wait_for_log 'document=' "it showed the library"
    grep -q 'title="Tool smoke test"' "$TOOL_LOG" \
        || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the app does not show the document the tool created"; }
    grep -q 'live=\[channel=open switch=on' "$TOOL_LOG" \
        || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the app did not open its channel for agents"; }
    echo "the app shows the document the tool created, and its channel for agents is open"
    run_tool 0 get "Tool smoke test"
    tool_said "Written by the bundled tool."
    echo "read while the app is open"
    run_tool 0 status
    sed 's/^/    /' "$TOOL_OUT"
    # Two changes while the app is open: to the document it shows, and a new document.
    run_tool 0 append "Tool smoke test" --content "Added while the app was open." --author Smoke
    sed 's/^/    /' "$TOOL_OUT"
    run_tool 0 create "Written while open" --content "Stored through the app." --author Smoke
    sed 's/^/    /' "$TOOL_OUT"
    # A tiny page, offline already: the tool checks it in WebKit and the app stores it.
    SMOKE_PAGE="$WORK/smoke-page"
    mkdir -p "$SMOKE_PAGE"
    printf '%s\n' '<!doctype html><html><head><meta charset="utf-8"><title>Smoke Page</title></head>' \
        '<body><h1>Smoke Page</h1><p>Kept whole by the bundled tool.</p></body></html>' >"$SMOKE_PAGE/index.html"
    run_tool 0 page add "$SMOKE_PAGE" --author Smoke
    sed 's/^/    /' "$TOOL_OUT"
    tool_said "added page:"
    wait_for_log 'the switch is off' "the changes of the tool had arrived"
    # The page is the last change. A change that arrives while the note of the one before
    # is still up joins it ("Smoke made 3 changes in the library"), which depends on how
    # long the check of the page took; either note is right.
    grep -qE 'changes=3 last="Smoke (added “Smoke Page”|made [23] changes in the library)"' "$TOOL_LOG" \
        || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the app did not count three changes by the tool, the page last"; }
    grep -q 'text: .*Added while the app was open\.' "$TOOL_LOG" \
        || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the text the tool appended is not in the window of the app"; }
    echo "the app made the three changes and shows the appended text"
    run_tool 0 list
    tool_said "Written while open"
    run_tool 0 get "Tool smoke test"
    tool_said "Added while the app was open."
    run_tool 0 get "Written while open"
    tool_said "Stored through the app."
    run_tool 0 pages
    tool_said "Smoke Page"
    run_tool 0 get "Smoke Page"
    tool_said "Kept whole by the bundled tool."
    echo "the three changes are in the library, the page with its text"
    # With the owner's switch off the old rule holds: a change is refused with the exit
    # code for "the app is open" (5), says why, and changes nothing. Reading goes on.
    grep -q 'live=\[channel=open switch=off' "$TOOL_LOG" \
        || { sed 's/^/    /' "$TOOL_LOG" >&2; die "the switch for changes by agents is not off"; }
    run_tool 5 create "Refused while open" --content "This must not be stored."
    sed 's/^/    /' "$TOOL_OUT"
    tool_said "switched off"
    run_tool 5 append "Tool smoke test" --content "This must not be stored."
    run_tool 5 page add "$SMOKE_PAGE" --title "Refused page" --author Smoke
    run_tool 0 list
    if grep -q "Refused page" "$TOOL_OUT"; then die "a page was added with the switch off"; fi
    if grep -q "Refused while open" "$TOOL_OUT"; then die "a document was created with the switch off"; fi
    run_tool 0 get "Tool smoke test"
    if grep -q "This must not be stored." "$TOOL_OUT"; then die "a document was changed with the switch off"; fi
    tool_said "Added while the app was open."
    echo "with the switch off changes were refused (exit code 5), and nothing was changed"
    # The MCP server of the tool, which the assistant's side chat starts for its read-only
    # tools, reads the library while the app has it open.
    MCP_OUT="$WORK/mcp.out"
    printf '%s\n' \
        '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"smoke","version":"0"}}}' \
        '{"jsonrpc":"2.0","method":"notifications/initialized"}' \
        '{"jsonrpc":"2.0","id":2,"method":"tools/call","params":{"name":"list_library","arguments":{}}}' \
        | "$BUNDLED_TOOL" --library "$TOOL_DATA" mcp >"$MCP_OUT" 2>&1 \
        || { sed 's/^/    /' "$MCP_OUT" >&2; die "the MCP server of the tool failed while the app was open"; }
    grep -q '"id":2' "$MCP_OUT" && grep -q 'Tool smoke test' "$MCP_OUT" \
        || { sed 's/^/    /' "$MCP_OUT" >&2; die "the MCP server did not list the library while the app was open"; }
    echo "the MCP server lists the library while the app is open"

    # The app is asked to quit the way "kill" asks: it saves and ends with status 0.
    kill -TERM "$APP_PID"
    wait_for_app "$TOOL_LOG"
    # And with the app closed again, the tool writes again.
    run_tool 0 append "Tool smoke test" --content "Added after the app was closed."
    run_tool 0 get "Tool smoke test"
    tool_said "Added after the app was closed."
    tool_said "Added while the app was open."
    echo "smoke test passed: the tool writes with the app closed, through the app while it is open, and only reads with the switch off"

    # The assistant, on the fake engine (which starts no program and spends nothing; the
    # real one is never used by this script): it is shown, the side chat takes a message
    # about the open document and gets its answer, and the tools it would be given are the
    # MCP server of the tool in this very bundle, on this library.
    step "Smoke test: the assistant in the bundled app, on the fake engine"
    ASSISTANT_LOG="$WORK/assistant-app.log"
    THE_WRITER_ASSISTANT_FAKE=ready \
    THE_WRITER_AUTOMATION="wait:1500; keys:cmd-p; type:Tool smoke; keys:enter; wait:300; keys:cmd-3; wait:300; type:Is this a test?; keys:enter; wait:600; state; quit" \
        "$APP/Contents/MacOS/$BIN_NAME" >"$ASSISTANT_LOG" 2>&1 &
    APP_PID=$!
    wait_for_app "$ASSISTANT_LOG"
    assistant_said() {
        grep -qF -- "$1" "$ASSISTANT_LOG" || die "the state of the app does not have: $1"
    }
    assistant_said 'assistant=[shown=true'
    assistant_said 'side=[document="Tool smoke test" messages=2 answering=false last=done'
    # The executable's path with its symbolic links resolved, as the app names the tool.
    RESOLVED_TOOL="$(cd "$APP/Contents/MacOS" && pwd -P)/$TOOL_NAME"
    RESOLVED_DATA="$(cd "$TOOL_DATA" && pwd -P)"
    grep -qF -- "tools=[$RESOLVED_TOOL --library $RESOLVED_DATA mcp]" "$ASSISTANT_LOG" \
        || grep -qF -- "tools=[$RESOLVED_TOOL --library $TOOL_DATA mcp]" "$ASSISTANT_LOG" \
        || die "the side chat's tools are not the MCP server of the bundled tool on this library"
    echo "smoke test passed: the assistant answers in the side chat, with the bundled tool as its tools"

    # The keyboard shortcuts: a key recorded in the list of the bundled app is in force,
    # is stored with the library, and is there at the next launch.
    step "Smoke test: a keyboard shortcut changed in the bundled app"
    KEYS_LOG="$WORK/keys-app.log"
    THE_WRITER_AUTOMATION="wait:1500; keys:cmd-/; wait:300; type:bold; wait:200; keys:enter; keys:cmd-alt-b; keys:enter; wait:300; state; quit" \
        "$APP/Contents/MacOS/$BIN_NAME" >"$KEYS_LOG" 2>&1 &
    APP_PID=$!
    wait_for_app "$KEYS_LOG"
    grep -qF -- 'selected="Bold" keys=[cmd-alt-b] default=[cmd-b] (changed)' "$KEYS_LOG" \
        || die "the list of keyboard shortcuts did not give Bold the key that was pressed"
    THE_WRITER_AUTOMATION="wait:1500; state; quit" \
        "$APP/Contents/MacOS/$BIN_NAME" >"$KEYS_LOG" 2>&1 &
    APP_PID=$!
    wait_for_app "$KEYS_LOG"
    grep -qF -- 'keys=[changed=1]' "$KEYS_LOG" \
        || die "the changed keyboard shortcut was not there at the next launch"
    unset THE_WRITER_DATA_DIR
    echo "smoke test passed: a key changed in the list is stored with the library and kept"
else
    step "Smoke test skipped (--no-smoke-test)"
fi

# ---------------------------------------------------------------- disk image
step "Building the disk image"
DMG_STAGE="$WORK/dmg"
mkdir -p "$DMG_STAGE"
ditto "$APP" "$DMG_STAGE/$APP_NAME.app"
ln -s /Applications "$DMG_STAGE/Applications"
cp "$README" "$DMG_STAGE/Read Me First.txt"
rm -f "$DMG"
# ULMO (lzma) needs macOS 10.15 to mount, which is also the app's minimum.
hdiutil create -volname "$APP_NAME" -srcfolder "$DMG_STAGE" -fs HFS+ -format ULMO -ov -quiet "$DMG"
hdiutil verify -quiet "$DMG"

step "Checking the disk image"
MOUNT_POINT="$WORK/mount"
mkdir -p "$MOUNT_POINT"
hdiutil attach "$DMG" -readonly -nobrowse -noautoopen -noverify -mountpoint "$MOUNT_POINT" -quiet
ls -la "$MOUNT_POINT" | sed 's/^/    /'
[[ -x "$MOUNT_POINT/$APP_NAME.app/Contents/MacOS/$BIN_NAME" ]] || die "the app is missing from the disk image"
[[ -x "$MOUNT_POINT/$APP_NAME.app/Contents/MacOS/$TOOL_NAME" ]] || die "the $TOOL_NAME tool is missing from the app in the disk image"
[[ -f "$MOUNT_POINT/Read Me First.txt" ]] || die "Read Me First.txt is missing from the disk image"
[[ "$(readlink "$MOUNT_POINT/Applications")" == "/Applications" ]] || die "the Applications link is missing from the disk image"
codesign --verify --deep --strict "$MOUNT_POINT/$APP_NAME.app" || die "the app inside the disk image fails signature verification"
codesign --verify --strict "$MOUNT_POINT/$APP_NAME.app/Contents/MacOS/$TOOL_NAME" || die "the $TOOL_NAME tool inside the disk image fails signature verification"
# The tool runs from the image as it stands (it only prints its version: no library is opened).
IMAGE_TOOL_VERSION="$("$MOUNT_POINT/$APP_NAME.app/Contents/MacOS/$TOOL_NAME" --version)"
[[ "$IMAGE_TOOL_VERSION" == "$TOOL_NAME $VERSION" ]] || die "the $TOOL_NAME tool inside the disk image says '$IMAGE_TOOL_VERSION', expected '$TOOL_NAME $VERSION'"
